window.applyI18n = function(lang) {
  const dict = window.I18N[lang] || window.I18N.uk;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] != null) {
      // preserve child elements when translation is text-only
      if (el.children.length === 0) {
        el.textContent = dict[key];
      } else {
        // For elements with children (like brand-text that has span inside),
        // only replace the first text node
        const firstText = [...el.childNodes].find(n => n.nodeType === 3);
        if (firstText) firstText.textContent = dict[key];
        else el.prepend(document.createTextNode(dict[key]));
      }
    }
  });
};
